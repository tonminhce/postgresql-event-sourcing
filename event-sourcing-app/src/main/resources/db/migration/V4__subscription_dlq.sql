CREATE TABLE IF NOT EXISTS ES_EVENT_SUBSCRIPTION_DEAD_LETTER (
  ID                  BIGSERIAL                 PRIMARY KEY,
  SUBSCRIPTION_NAME   TEXT                      NOT NULL,
  EVENT_ID            BIGINT                    NOT NULL REFERENCES ES_EVENT (ID),
  TRANSACTION_ID      XID8                      NOT NULL,
  AGGREGATE_TYPE      TEXT                      NOT NULL,
  EVENT_TYPE          TEXT                      NOT NULL,
  ERROR_MESSAGE       TEXT                      NOT NULL,
  STACK_TRACE         TEXT,
  RETRY_COUNT         INTEGER                   NOT NULL DEFAULT 0,
  CREATED_AT          TIMESTAMP WITH TIME ZONE  DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS IDX_ES_SUB_DLQ_NAME ON ES_EVENT_SUBSCRIPTION_DEAD_LETTER (SUBSCRIPTION_NAME);
CREATE INDEX IF NOT EXISTS IDX_ES_SUB_DLQ_EVENT_ID ON ES_EVENT_SUBSCRIPTION_DEAD_LETTER (EVENT_ID);
